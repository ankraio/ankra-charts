#!/usr/bin/env bash
# Sync a vendored chart with its upstream release and propose the result as a
# rolling pull request, one branch per chart family.
#
# Usage: ci/sync.sh <upcloud | digitalocean | cloudflare-operator | hermes-agent>
#
# On main the push and the pull request go through the run's git credential
# (the `charts_git` binding in .ankra/pipeline.yaml, the organisation's GitHub
# App). Anywhere else - a manual run of a branch - it is a dry run: it syncs,
# lints and prints the diff and the pull request it would open, and pushes
# nothing.
set -euo pipefail

# shellcheck source=ci/env.sh
source "$(dirname "$0")/env.sh"

target="${1:?usage: ci/sync.sh <upcloud | digitalocean | cloudflare-operator | hermes-agent>}"
repository="ankraio/ankra-charts"
credential_file="/run/agent-secrets/charts_git"
body_file="${CI_SCRATCH}/pull-request-body.md"
generated_by="Generated by the \`sync-${target}\` stage of [\`.ankra/pipeline.yaml\`](./.ankra/pipeline.yaml) on $(date -u +%Y-%m-%dT%H:%M:%SZ)."

is_publishing=false
case "${ANKRA_REF:-}" in
  main | refs/heads/main) is_publishing=true ;;
esac

GITHUB_TOKEN=""
if [[ -r "${credential_file}" ]]; then
  GITHUB_TOKEN="$(jq -r '.token // empty' "${credential_file}")"
fi
export GITHUB_TOKEN
if [[ "${is_publishing}" == true && -z "${GITHUB_TOKEN}" ]]; then
  echo "sync: no git credential reached this step, so the pull request cannot be opened." >&2
  echo "sync: the charts_git binding is a protected section; an organisation administrator approves it with" >&2
  echo "sync:   ankra pipeline definitions approve <definition-id>" >&2
  exit 1
fi

section() {
  printf '\n==> %s\n' "$*"
}

app_version() {
  grep -E '^appVersion:' "$1/Chart.yaml" | awk '{print $2}' | tr -d '"'
}

# run_sync <exit code variable> <command...>: exit 0 and 2 are both success; 2
# means the vendored YAML changed structurally and the pull request needs review.
run_sync() {
  local -n exit_code_reference="$1"
  shift
  exit_code_reference=0
  "$@" || exit_code_reference=$?
  if [[ "${exit_code_reference}" != 0 && "${exit_code_reference}" != 2 ]]; then
    exit "${exit_code_reference}"
  fi
}

github_api() {
  curl -fsSL \
    -H "Authorization: Bearer ${GITHUB_TOKEN}" \
    -H "Accept: application/vnd.github+json" \
    -H "X-GitHub-Api-Version: 2022-11-28" \
    "$@"
}

# propose <branch> <title> <labels, comma separated> <commit message> <paths...>
propose() {
  local branch="$1" title="$2" labels="$3" message="$4"
  shift 4

  section "proposed change"
  git --no-pager diff --stat -- "$@"
  echo
  echo "Title:  ${title}"
  echo "Branch: ${branch}"
  echo "Labels: ${labels}"
  echo
  cat "${body_file}"

  if [[ "${is_publishing}" != true ]]; then
    echo
    echo "dry run (${ANKRA_REF:-no ref}, not main): nothing is pushed"
    return 0
  fi

  section "pushing ${branch} and opening or updating the pull request"
  git checkout --quiet -B "${branch}"
  git add -A -- "$@"
  git \
    -c user.name="ankra-pipelines[bot]" \
    -c user.email="noreply@ankra.ai" \
    commit --quiet -m "${message}"
  # The token reaches git through a credential helper reading the environment,
  # never through the command line or the remote URL.
  # shellcheck disable=SC2016
  git \
    -c credential.helper= \
    -c 'credential.helper=!f() { echo username=x-access-token; echo "password=${GITHUB_TOKEN}"; }; f' \
    push --quiet --force "https://github.com/${repository}.git" "HEAD:refs/heads/${branch}"

  local number payload
  number="$(github_api "https://api.github.com/repos/${repository}/pulls?state=open&head=ankraio:${branch}" \
    | jq -r '.[0].number // empty')"
  payload="$(jq -n --arg title "${title}" --rawfile body "${body_file}" --arg head "${branch}" \
    '{title: $title, body: $body, head: $head, base: "main"}')"
  if [[ -n "${number}" ]]; then
    github_api -X PATCH "https://api.github.com/repos/${repository}/pulls/${number}" \
      -d "$(jq '{title, body}' <<< "${payload}")" > /dev/null
    echo "updated https://github.com/${repository}/pull/${number}"
  else
    number="$(github_api -X POST "https://api.github.com/repos/${repository}/pulls" -d "${payload}" | jq -r '.number')"
    echo "opened https://github.com/${repository}/pull/${number}"
  fi
  github_api -X POST "https://api.github.com/repos/${repository}/issues/${number}/labels" \
    -d "$(jq -n --arg labels "${labels}" '{labels: ($labels | split(","))}')" > /dev/null
}

has_changes() {
  ! git diff --quiet --exit-code -- "$@" || [[ -n "$(git ls-files --others --exclude-standard -- "$@")" ]]
}

sync_cloud_driver_pair() {
  local family="$1" display="$2" ccm_chart="$3" csi_chart="$4" ccm_command="$5" csi_command="$6"
  local ccm_source="$7" csi_source="$8"
  local ccm_exit_code=0 csi_exit_code=0

  section "syncing ${ccm_chart} and ${csi_chart} with upstream"
  run_sync ccm_exit_code ./scripts/sync-upstream.sh "${ccm_command}"
  run_sync csi_exit_code ./scripts/sync-upstream.sh "${csi_command}"

  if ! has_changes "${ccm_chart}" "${csi_chart}"; then
    echo "${display} charts are already up to date with upstream. Nothing to propose."
    return 0
  fi

  section "helm lint before proposing"
  if [[ "${family}" == upcloud ]]; then
    helm lint upcloud-ccm --set ccmConfig.clusterID=ci --set credentials.username=ci --set credentials.password=ci
    helm lint upcloud-csi
  else
    helm lint digitalocean-ccm --set credentials.token=ci
    helm lint digitalocean-csi --set credentials.token=ci
  fi

  local ccm_app csi_app labels
  ccm_app="$(app_version "${ccm_chart}")"
  csi_app="$(app_version "${csi_chart}")"
  {
    echo "Automated sync of ${ccm_chart} and ${csi_chart} against upstream ${display} releases."
    echo
    echo "| Chart | Current appVersion | Sync exit code | Source |"
    echo "|---|---|---|---|"
    echo "| ${ccm_chart} | \`${ccm_app}\` | \`${ccm_exit_code}\` | ${ccm_source//@VERSION@/${ccm_app}} |"
    echo "| ${csi_chart} | \`${csi_app}\` | \`${csi_exit_code}\` | ${csi_source//@VERSION@/${csi_app}} |"
    echo
    if [[ "${ccm_exit_code}" == 2 || "${csi_exit_code}" == 2 ]]; then
      echo "**Structural change detected** - vendored YAML changed in ways beyond image tags. **Manual review required.**"
    else
      echo "Tag-only diff - safe to merge once CI is green."
    fi
    echo
    echo "${generated_by}"
  } > "${body_file}"
  labels="automated,dependencies,${family}"
  if [[ "${ccm_exit_code}" == 2 || "${csi_exit_code}" == 2 ]]; then
    labels="${labels},needs-review"
  fi

  propose "chore/charts-${family}-sync" \
    "chore(${family}): sync to upstream ${display} releases" \
    "${labels}" \
    "chore(${family}): sync to upstream" \
    "${ccm_chart}" "${csi_chart}"
}

case "${target}" in
  upcloud)
    sync_cloud_driver_pair upcloud UpCloud upcloud-ccm upcloud-csi ccm csi \
      "https://github.com/UpCloudLtd/cloud-controller-manager (fallback: GHCR tags)" \
      "https://github.com/UpCloudLtd/upcloud-csi/releases/tag/@VERSION@"
    ;;

  digitalocean)
    sync_cloud_driver_pair digitalocean DigitalOcean digitalocean-ccm digitalocean-csi do-ccm do-csi \
      "https://github.com/digitalocean/digitalocean-cloud-controller-manager/releases/tag/@VERSION@" \
      "https://github.com/digitalocean/csi-digitalocean/releases/tag/@VERSION@"
    ;;

  cloudflare-operator)
    chart=cloudflare-operator
    section "syncing ${chart} with upstream"
    sync_exit_code=0
    run_sync sync_exit_code ./scripts/sync-upstream.sh cloudflare
    if ! has_changes "${chart}"; then
      echo "${chart} is already up to date with upstream. Nothing to propose."
      exit 0
    fi

    section "helm lint, render and unit tests before proposing"
    helm lint "${chart}"
    helm template ci-render "${chart}" --namespace cloudflare-operator-system \
      --set credentials.existingSecret=cloudflare-secrets > "${CI_SCRATCH}/cloudflare-render.yaml"
    grep -q 'kind: CustomResourceDefinition' "${CI_SCRATCH}/cloudflare-render.yaml"
    grep -q 'kind: Deployment' "${CI_SCRATCH}/cloudflare-render.yaml"
    helm unittest "${chart}"

    current="$(app_version "${chart}")"
    {
      echo "Automated sync of \`${chart}\` against upstream"
      echo "[adyanth/cloudflare-operator](https://github.com/adyanth/cloudflare-operator/releases)."
      echo
      echo "| Chart | Current appVersion | Sync exit code | Source |"
      echo "|---|---|---|---|"
      echo "| ${chart} | \`${current}\` | \`${sync_exit_code}\` | https://github.com/adyanth/cloudflare-operator/releases/tag/v${current} |"
      echo
      if [[ "${sync_exit_code}" == 2 ]]; then
        echo "**Structural change detected** - vendored \`cloudflare-operator.yaml\` changed in ways"
        echo "beyond image tags / digests (e.g. new RBAC rule, new container, deleted resource)."
        echo "**Manual review required** before merging."
      else
        echo "Tag-only diff (or no diff at all beyond image digests) - safe to merge once CI is green."
      fi
      echo
      echo "${generated_by}"
    } > "${body_file}"
    labels="automated,dependencies,cloudflare"
    if [[ "${sync_exit_code}" == 2 ]]; then
      labels="${labels},needs-review"
    fi
    propose "chore/charts-cloudflare-operator-sync" \
      "chore(cloudflare-operator): sync to upstream adyanth/cloudflare-operator" \
      "${labels}" \
      "chore(cloudflare-operator): sync to upstream" \
      "${chart}"
    ;;

  hermes-agent)
    # Two things can change: a newer CalVer tag upstream (appVersion moves), or
    # the pinned tag resolving to a new digest - the tag was moved under us,
    # which is a supply-chain event, not a release, and the pull request says
    # so. Either way the chart version gets a patch bump so the publish
    # workflow has something new to push.
    chart=hermes-agent
    before_tag="$(yq -r '.image.tag' "${chart}/values.yaml")"
    before_digest="$(yq -r '.image.digest' "${chart}/values.yaml")"
    before_chart_version="$(yq -r '.version' "${chart}/Chart.yaml")"

    section "resolving the newest ${chart} image"
    digest_exit_code=0
    run_sync digest_exit_code ./scripts/sync-image-digest.sh "${chart}" latest
    if ! has_changes "${chart}"; then
      echo "Pinned ${before_tag} still resolves to ${before_digest}. Nothing to propose."
      exit 0
    fi

    after_tag="$(yq -r '.image.tag' "${chart}/values.yaml")"
    after_digest="$(yq -r '.image.digest' "${chart}/values.yaml")"
    kind=new-release
    if [[ "${after_tag}" == "${before_tag}" ]]; then
      kind=tag-moved
    fi

    major="${before_chart_version%%.*}"
    rest="${before_chart_version#*.}"
    minor="${rest%%.*}"
    patch="${rest#*.}"
    after_chart_version="${major}.${minor}.$((patch + 1))"
    sed -i -E "0,/^version:.*$/s//version: ${after_chart_version}/" "${chart}/Chart.yaml"
    echo "${before_chart_version} -> ${after_chart_version} (${kind})"

    section "helm lint, render and unit tests before proposing"
    helm lint --strict "${chart}"
    helm template ci "${chart}" --namespace hermes --set secrets.existingSecret=hermes-credentials > /dev/null
    # The unit tests assert the pinned digest, so refresh them with the new one
    # rather than letting the pull request land red.
    grep -rl "${before_digest}" "${chart}/tests" \
      | xargs --no-run-if-empty sed -i "s|${before_tag}@${before_digest}|${after_tag}@${after_digest}|g"
    helm unittest "${chart}"

    {
      if [[ "${kind}" == tag-moved ]]; then
        echo "## The pinned tag moved"
        echo
        echo "\`${after_tag}\` now resolves to a different image."
        echo "The tag did not change, the contents did. **Review what changed upstream"
        echo "before merging** - this is the case digest pinning exists to catch."
      else
        echo "## New Hermes Agent release"
        echo
        echo "Upstream published \`${after_tag}\`."
      fi
      echo
      echo "| | Before | After |"
      echo "|---|---|---|"
      echo "| Image tag | \`${before_tag}\` | \`${after_tag}\` |"
      echo "| Image digest | \`${before_digest}\` | \`${after_digest}\` |"
      echo "| Chart version | \`${before_chart_version}\` | \`${after_chart_version}\` |"
      echo
      echo "Merging publishes \`hermes-agent-${after_chart_version}\` to GHCR and the Pages Helm repo."
      echo
      echo "${generated_by}"
    } > "${body_file}"
    labels="automated,dependencies,hermes-agent"
    if [[ "${kind}" == tag-moved ]]; then
      labels="${labels},needs-review,security"
    fi
    echo "sync-image-digest exit code: ${digest_exit_code}"
    propose "chore/charts-hermes-sync" \
      "chore(hermes-agent): pin ${after_tag} (${kind})" \
      "${labels}" \
      "chore(hermes-agent): pin ${after_tag}" \
      "${chart}"
    ;;

  *)
    echo "ci/sync.sh: unknown target ${target}" >&2
    exit 64
    ;;
esac
